"""Render the human task specification from the maintained execution catalog."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
catalog=json.loads((ROOT/'tasks/v2/catalog.json').read_text())
header='''# VideoICL 75 个 Web 交互任务

本规范覆盖 001—075，每题 A/B/C 三个视频规则版本，共 225 个条件；低、中、高各 25 题。视频用于明确教授规则，执行任务用于检验规则迁移和长程操作。三个版本保持业务初态与目标一致，只改变需要从视频学习的规则。

## 难度标准

| 难度 | 执行要求 | 必要依赖 | 不作为难度来源 |
| --- | --- | --- | --- |
| 低 | 在多个新对象或独立局面中反复应用同一规则，完成整批工作 | 每份资料分别处理并保存；遗漏任何工作项均不能完成任务 | 把导航、保存或确认按钮计为规则应用 |
| 中 | 完成一个有明确用途的长程业务任务，部分关键步骤必须依赖视频规则 | 有效业务请求与处理范围 → 规则相关业务操作 → 与独立资料关联 → 可直接使用的成果及交付记录 | 单纯增加对象数量，要求手抄编号，或附加没有用途的报告 |
| 高 | 跨多个应用、多个业务模块完成更长的完整流程 | 查找与关联来源 → 规则处理及业务产物 → 跨应用传递真实内容 → 正确接收对象的可追溯交付 | 仅显示跨平台链接、发送文件名、提交空完成标记，或让步骤依赖不必要的障碍 |

分级依据任务结构与真实依赖，不使用点击次数、等待时间或含糊规则作为替代。平台不会自动推断视频规则、代选正确对象或用评测反馈引导下一步。工作项允许返回修改，业务成果按实际状态评测。

低难度文本、选择和棋盘题包含三份独立工作项，分类题处理完整对象批次。中难度的独立资料应服务于成果用途：例如节目单关联播报介绍，课程安排关联教学目标，采购询价关联规格和需求数量，对账凭证关联真实交易。高难度的接收应用必须能使用来源应用产生的实际成果，不能仅凭出现两个应用名称满足标准。

## Demo 与 inference

Demo 展示输入、操作和可见结果，并覆盖足以区分规则的对照案例。分类包含命中与未命中案例，阈值包含边界，选择题让不同竞争属性对应不同候选，文本变换明确整段与逐词等作用范围。录制者可见本版本完整规则与逐步说明；执行者获得业务目标及“按照视频中的规则处理”的提示，应用状态不包含规则版本或标准答案。

所有执行难度的 Demo 都只呈现规则示例：输入、依据规则执行的操作、可见结果。录制从应用默认首页开始，保留进入规则页面的自然导航；不加入 inference 的资料汇总、跨应用办理或最终业务交付。视频和执行环境可以使用不同应用，但字段、对象及动作的对应关系须明确。平台的预览与执行入口均无需录屏。

示范组数表示独立规则案例的数量，不表示需要完成几轮长程业务。074 的六组示范分别在六张独立棋盘上各选一个落点；连续六个己方回合及复盘文档属于执行环境。069 需要展示从未满足条件到首次满足条件并停止的必要移动过程，以教清停止规则；训练复盘与交付属于执行环境。

主页可按题号、难度、平台排序，选择题目与版本后进入示范或执行环境。两种环境独立保存并可重置。执行结果检查覆盖正确对象、规则结果、来源关联、交付位置与内容、无关数据的保留，以及后续修改造成的过期成果。演示清晰度和实际操作体验由同事逐题核验；本分级不代表已测定的模型成功率。

类型：T 为文本或字段变换，C 为分类标注，S 为选择或排序，A 为条件动作。表中的平台按参与应用列出，具体往返流程见执行步骤。
'''
parts=[header]
def cell(s):return str(s).replace('|','\\|').replace('\n',' ')
for level,label in [('low','低'),('medium','中'),('hard','高')]:
 parts += [f'\n## {label}难度任务\n','| 编号与任务 | 类型 | 平台 | 难度 | 规则 A / B / C | demo 录什么 | inference 执行什么 | 最终交付 |','| --- | --- | --- | --- | --- | --- | --- | --- |']
 for t in catalog['tasks']:
  if t['difficulty']!=level:continue
  fields=[f"{t['id']:03d} {t['title']}",t['type'],' + '.join(t['platforms']),label,'；'.join(f'{v}：{t["variants"][v]}' for v in 'ABC'),t['demo']['instructions'],' → '.join(t['inference']['steps']),t['delivery']]
  parts.append('| '+' | '.join(map(cell,fields))+' |')
parts+=['''
## 设计参考

[OSWorld](https://osworld-v1.xlang.ai/)提供真实应用、跨应用工作流和基于执行状态的评测；[WebArena](https://github.com/web-arena-x/webarena)提供可自行部署的网站环境与功能结果评测；[ClawBench](https://github.com/TIGER-AI-Lab/ClawBench)覆盖日常在线业务任务。本规范借鉴真实业务目标、前后依赖和成果验证的设计方式，难度分级及 75 题具体流程由本项目定义。
''']
(ROOT/'VideoICL_75_web_tasks.md').write_text('\n'.join(parts))
